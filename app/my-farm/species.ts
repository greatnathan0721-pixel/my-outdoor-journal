export function speciesOf(index: number, englishLabel: string): Species | null {
  if (index >= 151 && index <= 268) {
    return { name: `狗狗（${englishLabel.split(",")[0]}）`, emoji: "🐕", category: "land" };
  }
  const entry = table[index];
  if (!entry) return null;
  const [name, emoji, category] = entry;
  return { name, emoji, category: category ?? (SKY_DEFAULT.has(index) ? "sky" : "water") };
}

